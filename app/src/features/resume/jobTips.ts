/** 根据意向岗位匹配 2-3 条信息差提示 */
export function getJobTips(targetRole: string): string[] {
  const role = targetRole.trim().toLowerCase()
  if (!role) return FALLBACK_TIPS.slice(0, 2)
  for (const rule of JOB_TIP_RULES) {
    if (rule.keywords.some((k) => role.includes(k))) {
      return rule.tips.slice(0, 3)
    }
  }
  return FALLBACK_TIPS
}
